<?php

/**
 * Regenerates database/schema/larastan/tables.sql from the SQLite schema
 * baseline. Static analysis only: Larastan infers model columns from
 * migrations or schema dumps, but its parser understands MySQL syntax only,
 * so it cannot read the PostgreSQL or SQLite dumps Laravel loads. This writes
 * plain `CREATE TABLE` column lists (names, coarse types, nullability).
 * Laravel never loads this file.
 *
 * Usage: php scripts/dev/larastan-schema.php
 */
$root = dirname(__DIR__, 2);
$pdo = new PDO('sqlite::memory:');
$pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
$pdo->exec((string) file_get_contents($root.'/database/schema/sqlite-schema.sql'));

$map = static function (string $type): string {
    $t = strtolower($type);

    return match (true) {
        // Booleans first: SQLite stores them as tinyint(1).
        str_contains($t, 'bool'), $t === 'tinyint(1)' => 'BOOLEAN',
        str_contains($t, 'int') => 'BIGINT',
        str_contains($t, 'real'), str_contains($t, 'floa'), str_contains($t, 'doub') => 'DOUBLE',
        str_contains($t, 'numeric'), str_contains($t, 'decimal') => 'DECIMAL(16,4)',
        str_contains($t, 'datetime'), str_contains($t, 'timestamp') => 'DATETIME',
        $t === 'date' => 'DATE',
        str_contains($t, 'blob') => 'BLOB',
        default => 'TEXT',
    };
};

$out = "-- Generated by scripts/dev/larastan-schema.php for static analysis only.\n";
$out .= "-- Do not edit; Laravel never loads this file.\n\n";
$tables = $pdo->query("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
    ->fetchAll(PDO::FETCH_COLUMN);
foreach ($tables as $table) {
    $columns = [];
    foreach ($pdo->query('PRAGMA table_info("'.$table.'")')->fetchAll(PDO::FETCH_ASSOC) as $column) {
        $null = ((int) $column['notnull'] === 1 && (int) $column['pk'] === 0) ? 'NOT NULL' : 'NULL';
        $columns[] = sprintf('  `%s` %s %s', $column['name'], $map((string) $column['type']), $null);
    }
    $out .= "CREATE TABLE `{$table}` (\n".implode(",\n", $columns)."\n);\n\n";
}

file_put_contents($root.'/database/schema/larastan/tables.sql', $out);
echo 'Wrote '.count($tables)." tables.\n";
